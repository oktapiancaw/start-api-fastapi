from pydantic_settings import (
    BaseSettings,
    SettingsConfigDict,
)


class ApplicationConfig(BaseSettings):
    model_config = SettingsConfigDict(
        env_nested_delimiter="__",
        env_file=".env",
        env_file_encoding="utf-8",
        extra="ignore",
    )

    host: str = "127.0.0.1"
    port: int = 8000
    output_dir: str = "./public/output"
